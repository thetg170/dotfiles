local keymap = vim.keymap.set

keymap("n", "<leader>w", "<cmd>w<cr>", { desc = "Save file" })
keymap("n", "<leader>q", "<cmd>q<cr>", { desc = "Quit window" })
keymap("n", "<esc>", "<cmd>nohlsearch<cr>", { desc = "Clear search highlight" })

keymap("n", "<leader>a", function()
  require("agent").send(false)
end, { desc = "Send file:line to agent" })
keymap("x", "<leader>a", function()
  require("agent").send(true)
end, { desc = "Send file:lines to agent" })

keymap("n", "<leader>k", "<nop>", { desc = "+kata" })
keymap("n", "<leader>kn", function()
  require("kata").next()
end, { desc = "Next due kata" })
keymap("n", "<leader>kp", function()
  require("kata").pick()
end, { desc = "Pick kata" })
keymap("n", "<leader>kb", function()
  require("kata").repair()
end, { desc = "Start repair kata" })
keymap("n", "<leader>kr", function()
  require("kata").test()
end, { desc = "Run kata tests" })
keymap("n", "<leader>kf", function()
  require("kata").finish()
end, { desc = "Finish and grade kata" })
keymap("n", "<leader>kd", function()
  require("kata").dashboard()
end, { desc = "Kata dashboard" })
keymap("n", "<leader>kc", function()
  require("kata").toggle_completion()
end, { desc = "Toggle kata completion" })
keymap("n", "<leader>kh", function()
  require("kata").toggle_hints()
end, { desc = "Toggle motion hints" })

keymap("n", "<leader>r", "<nop>", { desc = "+run" })
keymap("n", "<leader>rp", function()
  require("python_run").run_file()
end, { desc = "Run Python file" })
keymap("n", "<leader>ra", function()
  require("python_run").run_file_with_args()
end, { desc = "Run Python file with args" })
keymap("n", "<leader>rt", function()
  require("python_run").run_pytest()
end, { desc = "Run pytest" })
keymap("n", "<leader>rl", function()
  require("python_run").run_last()
end, { desc = "Re-run last Python command" })
